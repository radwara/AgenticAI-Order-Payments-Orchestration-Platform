#!/bin/sh
# Mechanical guard-rail checks on a change (agents/guardrails.md). POSIX sh plus python3 stdlib.
#   check-deps.sh deps <diff-file> <issue-body-file> | deps --pr <N> --base <sha>
#       Fails when go.mod, go.sum or pom.xml gain a coordinate (Go module path; Maven
#       artifactId in <dependency>/<plugin>/<parent>/<extension>) that the linked
#       ticket's "Constraints" does not name as a whole token. The diff needs full
#       context (git diff --unified=100000): "gain" = in the new file, not the old one,
#       so version bumps do not count. New transitive go.sum modules must be named too.
#       --pr reuses check-scope.sh for the ticket link/approval checks via a gh wrapper.
#   check-deps.sh size <numstat-file>|--base <sha> [limit]   default limit 600; lockfiles
#       (go.sum, *.lock, package-lock.json...) and header-verified generated files are
#       not counted. A file is generated only if one of its first 15 lines is a comment
#       carrying a generator marker (GENERATED_MARKERS, an ERE; default: Go "Code
#       generated ... DO NOT EDIT", protobuf, @generated); the name or directory never
#       matters. Generated files are listed in the output. A numstat-file has no file
#       contents to check, so only --base can exclude generated files.
#   check-deps.sh go-lcov <module-dir> <cover-profile>       lcov on stdout, for diff-cover;
#       header-verified generated files are left out (they must not count at 0%)
#   check-deps.sh go-untested <module-dir> <cover-profile> --base <sha>
#       Fails for a changed non-test, non-generated .go file of the module that is absent
#       from the cover profile (build tag, no tests) unless it declares no statements.
#       Changed files under testdata/ are flagged with a ::warning:: (never silently exempt).
set -eu

die() { printf '%s\n' "$*" >&2; exit 2; }
HERE=$(cd "$(dirname "$0")" && pwd)
TMPD=$(mktemp -d)
trap 'rm -rf "$TMPD"' EXIT INT TERM
export TMPD
# Python helper shared by size, go-lcov and go-untested: header-verified generated files.
cat >"$TMPD/genhdr.py" <<'PY'
import os, re
MARKERS = os.environ.get("GENERATED_MARKERS") or r"Code generated .*DO NOT EDIT|Generated by the protocol buffer compiler\.\s+DO NOT EDIT|@generated\b|<auto-generated"
HEADER = re.compile(r"^\s*(//|#|/\*|\*|<!--|--)\s*.*(" + MARKERS + ")")
def is_generated(text):  # a marker inside a comment in the first 15 lines
    return any(HEADER.match(line) for line in text.split("\n")[:15])
def is_generated_file(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f: return is_generated(f.read(4096))
    except OSError: return False
PY

cmd_deps() {
  if [ "${1:-}" = "--pr" ]; then
    [ "${3:-}" = "--base" ] || die "usage: deps --pr N --base SHA"
    REAL_GH=${GH:-gh}
    # Records the issue check-scope.sh resolves; stubs the files API (scope is another job).
    cat >"$TMPD/gh" <<WRAP
#!/bin/sh
case "\$1 \$2" in
  "issue view") out=\$("$REAL_GH" "\$@") || exit \$?; printf '%s\n' "\$out" >"$TMPD/issue.json"; printf '%s\n' "\$out" ;;
  "api --paginate") echo '[]' ;;
  *) exec "$REAL_GH" "\$@" ;;
esac
WRAP
    chmod +x "$TMPD/gh"
    GH="$TMPD/gh" sh "$HERE/check-scope.sh" --pr "${2:?pr number}" >/dev/null || die "ticket link validation failed"
    jq -r '.body // ""' "$TMPD/issue.json" >"$TMPD/body.md"
    git diff --unified=100000 "${4:?base sha}...HEAD" -- '*go.mod' '*go.sum' '*pom.xml' >"$TMPD/deps.diff"
    set -- "$TMPD/deps.diff" "$TMPD/body.md"
  fi
  [ -r "${1:-}" ] && [ -r "${2:-}" ] || die "usage: deps <diff-file> <issue-body-file>"
  python3 -I - "$1" "$2" <<'PY'
import re, sys
import xml.etree.ElementTree as ET

def files(diff):  # (path, old_lines, new_lines) per file of a full-context diff
    cur = None
    for raw in open(diff, encoding="utf-8", errors="replace").read().split("\n"):
        if raw.startswith("diff --git "):
            if cur: yield cur
            cur = {"path": raw.rsplit(" b/", 1)[-1], "old": [], "new": [], "hunk": False}
        elif cur is None: continue
        elif not cur["hunk"]: cur["hunk"] = raw.startswith("@@")
        elif raw.startswith("+"): cur["new"].append(raw[1:])
        elif raw.startswith("-"): cur["old"].append(raw[1:])
        elif raw.startswith(" "): cur["old"].append(raw[1:]); cur["new"].append(raw[1:])
    if cur: yield cur

def go_coords(lines, is_sum):
    out = set()
    for line in lines:
        toks = line.split("//")[0].split()
        if toks[:1] and toks[0] in ("module", "go", "toolchain", "godebug", "retract"): continue
        if toks[:1] and toks[0] in ("require", "replace", "exclude"): toks = toks[1:]
        if not toks or toks[-1] == "(": continue
        found = toks[:1]
        if not is_sum and "=>" in toks:  # replace: the target counts unless it is a local path
            found += [t for t in toks[toks.index("=>") + 1:][:1] if not t.startswith((".", "/"))]
        out.update(t for t in found if "/" in t or "." in t)
    return out

def pom_coords(lines):  # groupId:artifactId of every dependency/plugin/parent/extension, via a real XML parser
    src = "\n".join(lines)
    if not src.strip(): return set()
    if "<!DOCTYPE" in src or "<!ENTITY" in src: sys.exit("deps-check failed: pom.xml with DOCTYPE/ENTITY is rejected")
    try: root = ET.fromstring(src)
    except ET.ParseError as e: sys.exit(f"deps-check failed: pom.xml is not valid XML ({e})")
    out = set()
    for el in root.iter():
        tag = el.tag.rsplit("}", 1)[-1]
        if tag not in ("dependency", "plugin", "parent", "extension"): continue
        kid = {k.tag.rsplit("}", 1)[-1]: (k.text or "").strip() for k in el}
        if "${" in kid.get("groupId", "") + kid.get("artifactId", ""):
            sys.exit("deps-check failed: property-based groupId/artifactId (${...}) is rejected; spell the coordinates out")
        if kid.get("artifactId"):
            default = "org.apache.maven.plugins" if tag == "plugin" else "?"
            out.add((kid.get("groupId") or default) + ":" + kid["artifactId"])
    return out


text, grab = [], False  # the Constraints section of the ticket
for line in open(sys.argv[2], encoding="utf-8", errors="replace").read().replace("\r", "").split("\n"):
    if re.match(r"#+\s", line): grab = bool(re.match(r"#+\s*Constraints", line, re.I)); continue
    if grab: text.append(line)
text = "\n".join(text)
mentioned = lambda c: re.search(r"(?<![A-Za-z0-9._/-])" + re.escape(c) + r"(?![A-Za-z0-9_/-])", text)

bad = []
for f in files(sys.argv[1]):
    base = f["path"].rsplit("/", 1)[-1]
    if base in ("go.mod", "go.sum"): gained = go_coords(f["new"], base == "go.sum") - go_coords(f["old"], base == "go.sum")
    elif base == "pom.xml": gained = pom_coords(f["new"]) - pom_coords(f["old"])
    else: continue
    bad += [(f["path"], c) for c in sorted(gained) if not mentioned(c)]
for path, c in bad:
    print(f"UNAPPROVED DEPENDENCY: {c} (added in {path}) is not named in the ticket's Constraints", file=sys.stderr)
if bad: sys.exit("deps-check failed: name it in the ticket's Constraints (human edit) or remove it")
print("deps-check ok")
PY
}

cmd_size() {
  HEADREF=""; BASEREF=""
  if [ "${1:-}" = "--base" ]; then
    BASEREF=${2:?base sha}; HEADREF=HEAD
    git -c core.quotepath=off diff --numstat --no-renames "$BASEREF...HEAD" >"$TMPD/numstat"; shift 2
  else [ -r "${1:-}" ] || die "usage: size <numstat-file>|--base SHA [limit]"; cp "$1" "$TMPD/numstat"; shift; fi
  python3 -I - "$TMPD/numstat" "${1:-600}" "$HEADREF" "$BASEREF" <<'PY'
import os, re, subprocess, sys
sys.path.insert(0, os.environ["TMPD"])
import genhdr
LOCKFILE = re.compile(r"(^|/)(go\.sum|package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$|\.lock$")
numstat, limit, head, base = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
def header_of(path):  # new content, else the deleted file's old content
    for ref in filter(None, (head, base)):
        r = subprocess.run(["git", "show", f"{ref}:{path}"], capture_output=True)
        if r.returncode == 0: return r.stdout[:4096].decode("utf-8", "replace")
    return ""
total, skipped, generated = 0, 0, []
for line in open(numstat):
    add, dele, path = (line.rstrip("\n").split("\t", 2) + ["", "", ""])[:3]
    n = (int(add) if add.isdigit() else 0) + (int(dele) if dele.isdigit() else 0)  # binary files show "-"
    if LOCKFILE.search(path): skipped += n
    elif genhdr.is_generated(header_of(path)): skipped += n; generated.append((path, n))
    else: total += n
print(f"changed lines: {total} (limit {limit}; {skipped} lockfile/generated lines excluded)")
for path, n in generated[:20]: print(f"  generated (header-verified), not counted: {path} ({n} lines)")
if len(generated) > 20: print(f"  ... and {len(generated) - 20} more generated files")
if total > limit: sys.exit("size-check failed: diff too large; the ticket should be split (escalate)")
PY
}

cmd_golcov() {
  MODDIR=${1:?module dir (repo-relative)}; PROFILE=${2:?cover profile}
  [ -r "$PROFILE" ] && [ -r "$MODDIR/go.mod" ] || die "cannot read $PROFILE or $MODDIR/go.mod"
  MODPATH=$(sed -n 's/^module[[:space:]]\{1,\}//p' "$MODDIR/go.mod" | head -1 | tr -d '\r')
  python3 -I - "${MODDIR#./}" "$MODPATH" "$PROFILE" <<'PY'
import os, re, sys
sys.path.insert(0, os.environ["TMPD"])
import genhdr
moddir, modpath, profile = sys.argv[1:4]
hits = {}  # repo-relative path -> {line: count}
for line in open(profile):
    m = re.match(r"(.+):(\d+)\.\d+,(\d+)\.\d+ \d+ (\d+)$", line.strip())
    if not m or not m.group(1).startswith(modpath + "/"): continue  # also skips "mode:"
    prefix = "" if moddir in ("", ".") else moddir.rstrip("/") + "/"
    per = hits.setdefault(prefix + m.group(1)[len(modpath) + 1:], {})
    for n in range(int(m.group(2)), int(m.group(3)) + 1):
        per[n] = max(per.get(n, 0), int(m.group(4)))
for path in sorted(hits):
    if genhdr.is_generated_file(path): continue  # header-verified generated code is not measured
    print("TN:\nSF:" + path)
    for n in sorted(hits[path]): print(f"DA:{n},{hits[path][n]}")
    print("end_of_record")
PY
}

cmd_gountested() {
  MODDIR=${1:?module dir (repo-relative)}; PROFILE=${2:?cover profile}; [ "${3:-}" = "--base" ] || die "usage: go-untested <module-dir> <cover-profile> --base SHA"
  [ -r "$PROFILE" ] && [ -r "$MODDIR/go.mod" ] || die "cannot read $PROFILE or $MODDIR/go.mod"
  MODPATH=$(sed -n 's/^module[[:space:]]\{1,\}//p' "$MODDIR/go.mod" | head -1 | tr -d '\r')
  git -c core.quotepath=off diff --name-only --diff-filter=AM --no-renames "${4:?base sha}...HEAD" -- "$MODDIR" >"$TMPD/changed"
  python3 -I - "${MODDIR#./}" "$MODPATH" "$PROFILE" "$TMPD/changed" <<'PY'
import os, re, sys
sys.path.insert(0, os.environ["TMPD"])
import genhdr
moddir, modpath, profile, changed = sys.argv[1:5]
prefix = "" if moddir in ("", ".") else moddir.rstrip("/") + "/"
covered = {m.group(1)[len(modpath) + 1:] for m in (re.match(r"(.+?):\d+\.\d+,", l) for l in open(profile)) if m and m.group(1).startswith(modpath + "/")}

def blank(src):  # comments, strings and runes removed (newlines kept) so braces and keywords are code only
    out, i, n = [], 0, len(src)
    while i < n:
        two, c = src[i:i + 2], src[i]
        if two == "//":
            while i < n and src[i] != "\n": i += 1
        elif two == "/*":
            j = src.find("*/", i + 2); j = n if j < 0 else j + 2
            out.append("\n" * src.count("\n", i, j)); i = j
        elif c in "\"'`":
            j = i + 1
            while j < n and src[j] != c: j += 2 if (src[j] == "\\" and c != "`") else 1
            out.append("\n" * src.count("\n", i, j)); i = j + 1
        else: out.append(c); i += 1
    return "".join(out)

def has_statements(src):  # does any func (declaration or literal) have a non-empty body?
    code = blank(src)
    for m in re.finditer(r"\bfunc\b", code):
        i, depth = m.end(), 0
        while i < len(code):
            c = code[i]
            if c in "([": depth += 1
            elif c in ")]":
                depth -= 1
                if depth < 0: break  # a func type inside a parameter list: no body
            elif c == "\n" and depth == 0: break  # a func type: no body
            elif c == "{" and depth == 0:
                d, j = 1, i + 1
                while j < len(code) and d: d += (code[j] == "{") - (code[j] == "}"); j += 1
                if code[i + 1:j - 1].strip(): return True
                break
            i += 1
    return False

bad, flagged = [], []
for path in (l.strip() for l in open(changed)):
    rel = path[len(prefix):]
    if not path.endswith(".go") or path.endswith("_test.go") or not os.path.isfile(path): continue
    parts = rel.split("/")
    if "testdata" in parts[:-1]: flagged.append(path); continue
    if any(os.path.exists(os.path.join(prefix, *parts[:k], "go.mod")) for k in range(1, len(parts))): continue  # nested module
    if rel in covered or genhdr.is_generated_file(path): continue
    if has_statements(open(path, encoding="utf-8", errors="replace").read()): bad.append(path)
for p in flagged: print(f"::warning::{p}: changed file under testdata/ is not compiled or measured; it is not exempt from review")
for p in bad: print(f"UNTESTED: {p} is changed, has statements and is absent from the cover profile (build tag or no test); test it (CI runs go test with GO_TEST_TAGS)", file=sys.stderr)
if bad: sys.exit("untested-check failed")
print("untested-check ok")
PY
}

SUB=${1:-}; [ $# -eq 0 ] || shift
case "$SUB" in
  deps) cmd_deps "$@" ;;
  size) cmd_size "$@" ;;
  go-lcov) cmd_golcov "$@" ;;
  go-untested) cmd_gountested "$@" ;;
  *) die "usage: check-deps.sh deps|size|go-lcov|go-untested ... (see header)" ;;
esac
