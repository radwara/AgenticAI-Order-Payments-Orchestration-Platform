#!/bin/sh
# Script test for T-022 and T-028: the changed-lines coverage gate (Go cover profile ->
# check-deps.sh go-lcov -> diff-cover --fail-under=80) fails on a diff with an
# untested changed line and passes once it is covered.
# Needs go, git and diff-cover (pip install diff-cover==10.0.0; or DIFF_COVER=<path>).
set -u

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SCRIPT="$ROOT/scripts/check-deps.sh"
DIFF_COVER=${DIFF_COVER:-diff-cover}
FAILS=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT INT TERM

pass() { printf 'PASS: %s\n' "$1"; }
fail() { printf 'FAIL: %s\n' "$1"; FAILS=$((FAILS + 1)); }
command -v "$DIFF_COVER" >/dev/null 2>&1 || { echo "diff-cover not found (pip install diff-cover==10.0.0)" >&2; exit 1; }
command -v go >/dev/null 2>&1 || { echo "go not found" >&2; exit 1; }

REPO="$TMP/repo"
git init -q -b main "$REPO"
git -C "$REPO" config user.email t@example.invalid
git -C "$REPO" config user.name t
mkdir -p "$REPO/libs/m"
printf 'module example.com/m\n\ngo 1.22\n' >"$REPO/libs/m/go.mod"
printf 'package m\n\n// Add returns a+b.\nfunc Add(a, b int) int {\n\treturn a + b\n}\n' >"$REPO/libs/m/m.go"
printf 'package m\n\nimport "testing"\n\nfunc TestAdd(t *testing.T) {\n\tif Add(1, 2) != 3 {\n\t\tt.Fatal("bad")\n\t}\n}\n' >"$REPO/libs/m/m_test.go"
git -C "$REPO" add -A
git -C "$REPO" commit -qm base

# The CI gate: test with a profile, convert, diff-cover against the base.
gate() {
  (cd "$REPO/libs/m" && go test -coverprofile=cover.out ./... >/dev/null) || return 3
  (cd "$REPO" && sh "$SCRIPT" go-lcov libs/m libs/m/cover.out >"$TMP/lcov.info") || return 3
  (cd "$REPO" && "$DIFF_COVER" "$TMP/lcov.info" --compare-branch=main --fail-under=80)
}

printf '\n// Sign returns -1, 0 or 1.\nfunc Sign(n int) int {\n\tif n < 0 {\n\t\treturn -1\n\t}\n\tif n > 0 {\n\t\treturn 1\n\t}\n\treturn 0\n}\n' >>"$REPO/libs/m/m.go"
printf '\nfunc TestSignNegative(t *testing.T) {\n\tif Sign(-5) != -1 {\n\t\tt.Fatal("bad")\n\t}\n}\n' >>"$REPO/libs/m/m_test.go"
OUT=$(gate 2>&1); RC=$?
{ [ "$RC" -eq 1 ] && printf '%s' "$OUT" | grep -q 'm.go'; } && pass "gate fails when changed lines are untested" || fail "expected gate failure (rc=$RC): $OUT"

printf '\nfunc TestSignRest(t *testing.T) {\n\tif Sign(5) != 1 || Sign(0) != 0 {\n\t\tt.Fatal("bad")\n\t}\n}\n' >>"$REPO/libs/m/m_test.go"
OUT=$(gate 2>&1); RC=$?
[ "$RC" -eq 0 ] && pass "gate passes when the changed lines are covered" || fail "expected gate pass (rc=$RC): $OUT"

# T-028: generated files, build tags and untested files. Own repo so the cases above stay independent.
R2="$TMP/repo2"
git init -q -b main "$R2"
git -C "$R2" config user.email t@example.invalid
git -C "$R2" config user.name t
mkdir -p "$R2/libs/g/gen" "$R2/libs/g/testdata"
printf 'module example.com/g\n\ngo 1.22\n' >"$R2/libs/g/go.mod"
printf 'package g\n\n// One returns 1.\nfunc One() int {\n\treturn 1\n}\n' >"$R2/libs/g/g.go"
printf 'package g\n\nimport "testing"\n\nfunc TestOne(t *testing.T) {\n\tif One() != 1 {\n\t\tt.Fatal("bad")\n\t}\n}\n' >"$R2/libs/g/g_test.go"
git -C "$R2" add -A
git -C "$R2" commit -qm base
git -C "$R2" checkout -q -b feature
commit2() { git -C "$R2" add -A; git -C "$R2" commit -qm "$1"; }
# The full CI gate for libs/g: tests (optionally with -tags), lcov, untested-file check, diff-cover.
gate2() {
  (cd "$R2/libs/g" && go test -tags "$1" -coverprofile=cover.out ./... >/dev/null) || return 3
  (cd "$R2" && sh "$SCRIPT" go-lcov libs/g libs/g/cover.out >"$TMP/lcov2.info") || return 3
  (cd "$R2" && sh "$SCRIPT" go-untested libs/g libs/g/cover.out --base main) || return 1
  (cd "$R2" && "$DIFF_COVER" "$TMP/lcov2.info" --compare-branch=main --fail-under=80)
}

printf '//go:build integration\n\npackage g\n\n// Two returns 2.\nfunc Two() int {\n\treturn 2\n}\n' >"$R2/libs/g/two.go"; commit2 tagged
OUT=$(gate2 "" 2>&1); RC=$?
{ [ "$RC" -eq 1 ] && printf '%s' "$OUT" | grep -q 'UNTESTED: libs/g/two.go'; } && pass "changed file behind a build tag, absent from the profile -> fail" || fail "expected untested failure (rc=$RC): $OUT"
printf '//go:build integration\n\npackage g\n\nimport "testing"\n\nfunc TestTwo(t *testing.T) {\n\tif Two() != 2 {\n\t\tt.Fatal("bad")\n\t}\n}\n' >"$R2/libs/g/two_test.go"; commit2 tagged-test
OUT=$(gate2 "integration" 2>&1); RC=$?
[ "$RC" -eq 0 ] && pass "the same file with tests (run with its tag) -> pass" || fail "expected pass (rc=$RC): $OUT"

# Generated protobuf-style files at 0% never fail the gate; a hand-written file in gen/ does.
printf '// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.12\n// source: v1/p.proto\n\npackage gen\n\n// GetName returns the name.\nfunc GetName() string {\n\tif true {\n\t\treturn "a"\n\t}\n\treturn "b"\n}\n' >"$R2/libs/g/gen/p.pb.go"
printf '// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n\npackage gen\n\n// Serve serves.\nfunc Serve() int {\n\treturn 3\n}\n' >"$R2/libs/g/gen/p_grpc.pb.go"; commit2 generated
OUT=$(gate2 "integration" 2>&1); RC=$?
{ [ "$RC" -eq 0 ] && ! grep -q 'gen/' "$TMP/lcov2.info"; } && pass "generated protobuf files at 0% do not fail and are not in the lcov" || fail "expected pass (rc=$RC): $OUT"
printf 'package gen\n\n// Hand returns 4.\nfunc Hand() int {\n\treturn 4\n}\n' >"$R2/libs/g/gen/foo_gen.go"; commit2 handwritten
OUT=$(gate2 "integration" 2>&1); RC=$?
[ "$RC" -ne 0 ] && pass "hand-written foo_gen.go in gen/ is counted and fails at 0%" || fail "expected failure: $OUT"
git -C "$R2" rm -q libs/g/gen/foo_gen.go; commit2 drop-handwritten

# Declarations only are exempt; testdata is flagged, not silently exempt.
printf 'package g\n\n// Limit is a bound.\nconst Limit = 3\n\n// Handler is a func type.\ntype Handler func(int) error\n\n// Store has a method set.\ntype Store interface {\n\tGet(cb func(int)) error\n}\n' >"$R2/libs/g/decls.go"
printf 'package td\n\nfunc F() int {\n\treturn 1\n}\n' >"$R2/libs/g/testdata/f.go"; commit2 decls
OUT=$(gate2 "integration" 2>&1); RC=$?
{ [ "$RC" -eq 0 ] && printf '%s' "$OUT" | grep -q '::warning::libs/g/testdata/f.go'; } && pass "declarations-only file passes; testdata file is flagged" || fail "expected pass with warning (rc=$RC): $OUT"
printf 'package g\n\n// Run holds a func literal with statements.\nvar Run = func() int {\n\treturn 5\n}\n' >"$R2/libs/g/lit.go"; commit2 literal
OUT=$(gate2 "integration" 2>&1); RC=$?
{ [ "$RC" -ne 0 ] && printf '%s' "$OUT" | grep -q 'libs/g/lit.go'; } && pass "an untested func literal is caught (by the profile or the untested check)" || fail "expected untested failure (rc=$RC): $OUT"

[ "$FAILS" -eq 0 ] || { printf '%s test(s) failed\n' "$FAILS"; exit 1; }
echo "all tests passed"
